/**
 * Maintainer-curated baseline persona catalog.
 *
 * The shared reference set every maintainer and paid tester switches between.
 * Each entry carries a `dimension` (the group it is listed under), a `purpose`
 * (why a tester switches to it), a `testingUsage` (the page to open, the
 * action to take and the outcome to see), `stories` (the user-story ids it
 * serves, the key automated success-criterion tests select on), and
 * `coverageNotes` (the states it seeds, in plain words). The catalog doubles
 * as a coverage matrix that surfaces gaps as the testing surface grows. New
 * test slices add personas here rather than inventing fixture rows.
 *
 * Every entry's text is read by a tester on /dev/personas, so it names pages,
 * buttons and outcomes, never table or column names. A persona that pairs with
 * another names it by slug, and comes after it in the list when it depends on
 * rows the other seeds.
 *
 * Classes whose backing feature is not built yet (event organizers, group
 * roles, voting, the claimed-legacy banned subject) appear with a `blockedBy`
 * marker: they are never seeded and render greyed on /dev/personas, so the
 * catalog shows the full matrix and the test cases that arrive with each
 * future feature. Drop a persona's `blockedBy` when its feature lands.
 */
