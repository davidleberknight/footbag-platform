#!/usr/bin/env bash
# Rebuild every freestyle table from the committed inputs in freestyle/inputs/.
# Needs no mirror and no network: the footbag.org move corpus is the committed
# snapshot, not a live scrape. Idempotent and safe to re-run: loaders are
# DELETE+INSERT except loader 10 (records), which is additive (INSERT OR IGNORE,
# no DELETE), so record edits take effect only on a fresh DB build.
#
# Usage:  freestyle/run_freestyle.sh [path/to/footbag.db]   (default: database/footbag.db)
#
# The symbolic-grammar layer is loaded into the DB (26_load_symbolic_grammar.py)
# from committed CSVs under freestyle/symbolic_grammar/ and read from the DB at
# runtime, so the build never reads exploration/. All but glossary_crosslinks.csv,
# which is hand-authored, are regenerated by scripts/build_symbolic_grammar_2.py
# reading the database read-only; that is a manual dev-time step, not part of this
# rebuild. exploration/ is research-only and is never a required build input.
set -euo pipefail
cd "$(dirname "$0")/.."          # repo root
# shellcheck source=../scripts/lib/closing-report.sh
source scripts/lib/closing-report.sh

DB="${1:-database/footbag.db}"
PY_BIN="${PYTHON:-python3}"
L="freestyle/loaders"
S="freestyle/scripts"
I="freestyle/inputs"

# Every stage below is written "${PY}" <script> <args>, and PY names this
# function rather than the interpreter, so each stage runs with its output shown
# and then read: an error line, a warning line or a skipped row it printed is
# listed in the closing report, and a non-zero exit fails the rebuild there. The
# loaders mark a row they could not take with a bare SKIP, which the shared
# notice grammar does not match. The trick-dictionary QC ends with a count
# summary naming its review rows, "WARN 0" on a clean dictionary, so a WARN here
# must be followed by a colon or by a count above zero.
#
# The media-coverage QC is the one advisory stage. It audits the curated MEDIA
# layer (orphan tags, source registration), not the trick-table rebuild, and
# currently reports pre-existing media-data cleanup items, so its failure does
# not fail the rebuild; it is listed as a warning carrying the check's own last
# line, so the cleanup it reports stays in front of whoever reads the report.
LOADER_WARNINGS="${FOOTBAG_NOTICE_GRAMMAR//"WARN[: ]"/"WARN(:|[[:space:]][1-9])"}|(^|[[:space:]])SKIP[: ]"
ADVISORY_STAGES=" 24_qc_freestyle_media_coverage.py "
run_stage() {
  local name
  name="$(basename "$1")"
  if [[ "$ADVISORY_STAGES" == *" ${name} "* ]]; then
    cr_tolerate "${name} (advisory)" -- "${PY_BIN}" "$@"
  else
    cr_run --warnings "$LOADER_WARNINGS" "$name" -- "${PY_BIN}" "$@"
  fi
}
PY=run_stage

# Production-safety guard: this rebuild wipes and reloads every freestyle table,
# so it refuses to run against anything but this checkout's own development
# database. There is no bypass flag; at go-live the live database becomes the
# source of truth and this pipeline retires, deleted once the final production
# load is signed off.
cr_run "dev-database guard" -- bash freestyle/_assert_dev_db.sh "${DB}"

echo "→ Rebuilding freestyle tables into ${DB}"

# Records
"${PY}" "${L}/10_load_freestyle_records_to_sqlite.py"   --db "${DB}" --records-csv "${I}/curated/records/records_master.csv"
"${PY}" "${L}/11_load_consecutive_records_to_sqlite.py" --db "${DB}"

# Trick dictionary: curated-v1 base, then Red overlays, then footbag.org provenance + pending
# Preflight before any trick row is written: settle who owns what, refuse a slug
# a curator holds or nobody has classified, and move a row between committed
# producers where an input has handed it over.
"${PY}" "${L}/16_preflight_trick_ownership.py"      --db "${DB}"
"${PY}" "${L}/17_load_trick_dictionary.py"          --db "${DB}" --stage tricks
"${PY}" "${L}/19_load_red_additions.py"             --db "${DB}"

# The base dictionary's aliases sit here, between the overlay and the intake.
# After the overlay, because several name tricks it creates and renames, and an
# alias resolved against a half-built dictionary is silently skipped. Before the
# intake, because the intake reads the alias table to decide which scraped names
# are already curated; run it first and it creates pending rows for moves the
# dictionary already holds.
"${PY}" "${L}/17_load_trick_dictionary.py"          --db "${DB}" --stage aliases

"${PY}" "${L}/20_link_footbag_org_sources.py"       --db "${DB}"
"${PY}" "${L}/21_load_footbag_org_pending_tricks.py" --db "${DB}"

# Additive curated aliases (new rows no source loader produces), then curated
# alias-type / display overrides, both after every alias source loader.
"${PY}" "${L}/21a_load_alias_additions.py"          --db "${DB}"
"${PY}" "${L}/21b_apply_alias_overrides.py"         --db "${DB}"

# Retirement last: a trick is stale only when no committed input wants it, which
# cannot be known until every producer has written. Curator tricks and
# unclassified rows are never in reach.
"${PY}" "${L}/21c_retire_stale_tricks.py"           --db "${DB}"

# Emerging Vocabulary rulings: the adjudication record for observational names,
# seeded from the committed ruling ledger. Runs after every dictionary loader
# because the rulings that name a trick row link to it by foreign key, and the
# targets are rows 17, 19 and 21 create.
"${PY}" "${L}/28_load_ev_adjudications.py"          --db "${DB}"

# Parser population (structural_parse_json + computed_adds)
"${PY}" "${S}/parse_freestyle_notation.py" --apply --db "${DB}"

# Symbolic-grammar observational layer (read at runtime by symbolicGrammarService)
"${PY}" "${L}/26_load_symbolic_grammar.py" --db "${DB}"

# Trick-dictionary QC: hard gate (non-zero exit aborts the rebuild)
"${PY}" "${L}/22_qc_trick_dictionary.py"        --db "${DB}"

# Media-coverage QC: advisory, so run_stage lists a failure as a warning rather
# than failing the rebuild (see ADVISORY_STAGES above).
"${PY}" "${L}/24_qc_freestyle_media_coverage.py" --db "${DB}"

# Media-tag invariant: hard gate on this path. The script is a refusal by
# design, and a tripwire whose alarm is wired to an echo is not a tripwire.
# Note the limit: on a reset the curator seeder runs after this rebuild, so
# here the check sees an empty media table and passes on nothing. What it
# guards is a refresh against a database that already holds media.
"${PY}" "${L}/25_qc_media_tag_invariant.py"     --db "${DB}"

echo "→ Freestyle rebuild complete."
cr_proved "the trick-dictionary QC and the media-tag invariant passed over ${DB}"
cr_finish
