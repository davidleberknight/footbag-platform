/**
 * Staged freestyle set content: every canonical set the Set Encyclopedia lists and
 * gives a page, with its set group, display order, formula, plain explanation and
 * related sets. Loader 28a seeds it into freestyle_sets; after that the set editor
 * owns every value. A related set's label is the text its link shows; an empty
 * label shows the related set's own name. The set groups and their text are page
 * prose and stay in code; a set's group names one of them.
 */

export interface StagedRelatedSet {
  slug:  string;
  label: string;
}

export interface StagedSet {
  slug:         string;
  displayName:  string;
  setGroup:     string;
  sortOrder:    number;
  /** Empty when the set's notation is pending. */
  formula:      string;
  explanation:  string;
  relatedSets:  readonly StagedRelatedSet[];
  /** Kept off the encyclopedia list while its set status is undecided; its page still resolves. */
  heldFromList: boolean;
}

